import {readFileSync} from 'node:fs';
import {webcrypto,createHash} from 'node:crypto';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const key='test-only-preview-key';
const worker=readFileSync('_worker.js','utf8').replace(/const previewHash = "[a-f0-9]+";/, 'const previewHash = '+JSON.stringify(createHash('sha256').update(key).digest('hex'))+';');
const context={crypto:webcrypto,TextEncoder,URL,Response};
vm.createContext(context);
vm.runInContext(worker.replace('export default {','globalThis.worker = {'),context);
const env={ASSETS:{fetch:()=>new Response('unchanged static asset')}};
const request=(path,cookie,host='example.com')=>context.worker.fetch(new Request('https://'+host+path,{headers:cookie?{Cookie:cookie}:{}}),env);
for(const path of ['/programma','/programma/','/programma/index.html','/preview','/preview?key=wrong']) assert.equal((await request(path)).status,404);
const login=await request('/preview?key='+key);
assert.equal(login.status,303);
assert.equal(login.headers.get('Location'),'/programma');
const cookie=login.headers.get('Set-Cookie');
assert.match(cookie,/HttpOnly; Secure; SameSite=Lax/);
const page=await request('/programma',cookie.split(';')[0]);
assert.equal(page.status,200);
assert.equal(page.headers.get('Cache-Control'),'private, no-store');
const html=await page.text();
assert.equal(html,execFileSync('git',['show','bae0c79c61d93d822efae1e889152a4713f6d9e5:index.html'],{encoding:'utf8',maxBuffer:2000000}).replace('<a href="wachtlijst/">Wachtlijst</a>',''));
assert.match(html,/Combifit Community/);
assert.match(html,/Combifit Persoonlijk/);
assert.ok(!html.includes('combifit-waitlist-form'));
assert.ok(!html.includes('waitlist.js'));
assert.ok(!html.toLowerCase().includes('wachtlijst'));
assert.equal(await (await request('/wachtlijst/')).text(),'unchanged static asset');
assert.equal(await (await request('/review1.webp')).text(),'unchanged static asset');
console.log('Passed: unauthorized routes blocked, preview cookie, exact approved landing HTML, both packages, no waitlist, unchanged static routing.');

const host='online.jjscombifitdriel.nl';
const publicPage=await request('/',undefined,host);
assert.equal(publicPage.status,200);
assert.equal(publicPage.headers.get('X-Robots-Tag'),null);
assert.ok((await publicPage.text()).includes('Combifit Community'));
assert.equal((await request('/index.html',undefined,host)).headers.get('Location'),'/');
const customLogin=await request('/preview?key='+key,undefined,host);
assert.equal(customLogin.headers.get('Location'),'/');
assert.equal((await request('/',cookie.split(';')[0],host)).status,200);
assert.equal((await request('/index.html',cookie.split(';')[0],host)).headers.get('Location'),'/');
assert.equal((await request('/')).headers.get('Location'),'/wachtlijst/');
console.log('Passed: custom domain root is protected sales landing; Pages homepage remains waitlist; preview opens correct domain root.');
